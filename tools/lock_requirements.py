#!/usr/bin/env python3
"""Regenerate src/app/requirements.lock: every dependency pinned to an exact version with SHA-256 hashes of every wheel.

The installer and the updater install ONLY from this file, with `--require-hashes --only-binary :all:`, so a clean Mac never compiles
anything (no Xcode / Command Line Tools) and a swapped package on PyPI is rejected. Run it whenever requirements*.txt change, review the
diff, and commit. The file name's digest (first 16 hex of its SHA-256) is the `runtime_id` signed into each release.

    python tools/lock_requirements.py            # needs `uv` on the machine that runs it (a developer or CI, never an end user)

The lock is *universal* (valid for any platform); uv's macOS target resolver assumes macOS 13 and would reject mlx wheels (macOS 14+),
so a universal lock is used and the Mac picks its own wheels at install time.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "src" / "app"
# Versions verified on the production Mac (docs/06): mlx 0.32.4, mlx-audio 0.6.3, mlx-whisper 0.4.3, transformers 5.21.0, huggingface-hub 2.3.0
CONSTRAINTS = "mlx==0.32.4\nmlx-audio==0.6.3\nmlx-whisper==0.4.3\ntransformers==5.21.0\nhuggingface-hub==2.3.0\npydantic==2.14.1\npydantic-core==2.50.1\n"
# huggingface-hub 2.4.0 / transformers 5.21.1 broke queue synthesis on the Mac ("Tokenizer not loaded"); the 2.3.0 / 5.21.0 pair is the verified one.
HEADER = ("# Generated by tools/lock_requirements.py from requirements.txt + requirements-mlx.txt. Do not edit by hand.\n"
          "# Install with: uv pip install --require-hashes --only-binary :all: -r requirements.lock\n")


def main() -> int:
    uv = shutil.which("uv")
    if not uv:
        print("uv is required to regenerate the lock (developer/CI machines only).", file=sys.stderr)
        return 2
    with tempfile.TemporaryDirectory() as td:
        cons = Path(td) / "constraints.txt"
        cons.write_text(CONSTRAINTS)
        out = Path(td) / "requirements.lock"
        cmd = [uv, "pip", "compile", "requirements.txt", "requirements-mlx.txt", "-c", str(cons), "--universal", "--python-version", "3.12",
               "--generate-hashes", "--only-binary", ":all:", "--no-header", "-o", str(out)]
        r = subprocess.run(cmd, cwd=APP)
        if r.returncode != 0:
            return r.returncode
        body = out.read_text("utf-8").replace("\r\n", "\n")
        # uv records the absolute temp path of the constraints file in its "# via -c ..." comments; that would publish the developer's
        # local account name and change the lock (and therefore the runtime id) on every run
        body = re.sub(r"-c \S*constraints\.txt", "-c constraints.txt", body)
        text = HEADER + body
    (APP / "requirements.lock").write_bytes(text.encode("utf-8"))
    print(f"wrote {APP / 'requirements.lock'} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
